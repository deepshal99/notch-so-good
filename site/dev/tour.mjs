// v3 visual pass. usage: node site/dev/tour3.mjs <outdir> [w h]
import { createRequire } from 'module';
const require = createRequire(new URL('../../launch-film/package.json', import.meta.url));
const { chromium } = require('playwright');
const [out, w = 1440, h = 900] = process.argv.slice(2);
const b = await chromium.launch({ args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: +w, height: +h }, deviceScaleFactor: 2 });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
const shot = async (n, wait = 700, full = false) => { await p.waitForTimeout(wait); await p.screenshot({ path: `${out}/${n}.png`, fullPage: full }); console.log('shot', n); };
await p.goto('http://127.0.0.1:8787/index.html');
await p.mouse.move(+w * 0.72, +h * 0.62);
await shot('01-notch', 500);
await shot('02-pill', 2200);
await shot('03-sessions', 3600);
await p.waitForSelector('#island .layer.in [data-act=allow]', { timeout: 20000 });
await shot('04-approve', 2000);
await p.click('#island .layer.in [data-act=allow]');
await p.waitForSelector('#island .layer.in [data-reply] input', { timeout: 20000 });
await shot('05-done', 1200);
await p.evaluate(() => window.nsgDebug.usage(16.2));
await p.fill('#island .layer.in [data-reply] input', 'Now add a test');
await p.press('#island .layer.in [data-reply] input', 'Enter');
await shot('06-low', 5200);
await p.evaluate(() => window.nsgDebug.usage(0.5));
await shot('07-out', 9500);
await p.evaluate(() => document.querySelector('#features').scrollIntoView());
await shot('08-features', 2600);
await p.evaluate(() => scrollBy(0, 480));
await shot('09-features-low', 2600);
await p.evaluate(() => document.querySelector('#panel').scrollIntoView({ block: 'center' }));
await shot('10-panel', 3200);
await p.evaluate(() => { document.querySelectorAll('.tile').forEach(t => t.classList.add('seen')); scrollTo(0, 0); });
await shot('11-full', 1500, true);
console.log('errors:', errs.length ? errs : 'none');
await b.close();
